import re

def clean_sql(raw_sql_path, output_path):
    with open(raw_sql_path, 'r') as f:
        content = f.read()
    
    # Split by statements
    statements = [s.strip() + ';' for s in content.split(';') if s.strip()]
    
    tables = []
    constraints = []
    
    for stmt in statements:
        if stmt.startswith('create table'):
            tables.append(stmt)
        elif stmt.startswith('alter table'):
            constraints.append(stmt)
    
    # Add faculty table explicitly since it's used by JdbcTemplate
    faculty_table = """create table faculty (
    faculty_id bigint generated by default as identity primary key,
    first_name varchar(100) not null,
    last_name varchar(100) not null,
    official_email varchar(150) not null unique,
    department_id bigint,
    is_active boolean default true,
    created_at timestamp(6) with time zone default current_timestamp,
    updated_at timestamp(6) with time zone default current_timestamp
);"""
    tables.append(faculty_table)
    
    # Format nicely
    final_sql = "-- V1 Baseline Schema\n\n"
    final_sql += "-- TABLES\n"
    for t in tables:
        final_sql += t + "\n\n"
        
    final_sql += "-- CONSTRAINTS\n"
    for c in constraints:
        final_sql += c + "\n"
        
    with open(output_path, 'w') as f:
        f.write(final_sql)

if __name__ == "__main__":
    clean_sql('../scratch/raw_pg_schema.sql', 'src/main/resources/db/migration/V1__baseline_erp_schema.sql')
